"""
Inkscape Extension: Merge Connected Paths by Stroke Color

Menggabungkan path yang diselect berdasarkan:
1. Warna stroke yang sama
2. Ujung path yang berdekatan (dalam toleransi jarak)

Author: Generated by Kimi K2.6
"""

import inkex
from inkex import paths
from lxml import etree
import math

class MergeConnectedPaths(inkex.EffectExtension):

    def add_arguments(self, pars):
        pars.add_argument("--tolerance", type=float, default=1.0,
                          help="Toleransi jarak minimal antara ujung path (px)")

    def get_stroke_color(self, node):
        """Ambil warna stroke dari node, fallback ke 'none' jika tidak ada."""
        style = node.style
        if style:
            stroke = style.get('stroke')
            if stroke and stroke != 'none':
                return stroke.lower().strip()
        # Cek atribut stroke langsung
        stroke_attr = node.get('stroke')
        if stroke_attr and stroke_attr != 'none':
            return stroke_attr.lower().strip()
        return 'none'

    def get_path_endpoints(self, node):
        """Ambil koordinat ujung-ujung path (start dan end point)."""
        path_data = node.get('d', '')
        if not path_data:
            return None

        try:
            path_obj = paths.Path(path_data)
            if not path_obj:
                return None

            # Ambil first dan last point dari path
            first_cmd = path_obj[0]
            last_cmd = path_obj[-1]

            # Dapatkan absolute coordinates
            # Start point: first command's first point
            start_point = self._get_point_coords(first_cmd, node)
            # End point: last command's last point  
            end_point = self._get_point_coords(last_cmd, node, is_end=True)

            return (start_point, end_point)
        except Exception as e:
            inkex.utils.errormsg(f"Error parsing path: {e}")
            return None

    def _get_point_coords(self, cmd, node, is_end=False):
        """Ekstrak koordinat point dari command path."""
        # Simplified: extract x,y from command
        # Handle transform
        transform = node.transform

        if hasattr(cmd, 'x') and hasattr(cmd, 'y'):
            x, y = cmd.x, cmd.y
        elif len(cmd) >= 2:
            # Try to get last coordinate pair
            coords = list(cmd)
            if len(coords) >= 2:
                x, y = coords[-2], coords[-1]
            else:
                return None
        else:
            return None

        # Apply transform jika ada
        if transform:
            point = transform.apply_to_point((x, y))
            return point
        return (x, y)

    def distance(self, p1, p2):
        """Hitung jarak Euclidean antara dua point."""
        if p1 is None or p2 is None:
            return float('inf')
        return math.sqrt((p1[0] - p2[0])**2 + (p1[1] - p2[1])**2)

    def merge_two_paths(self, path1_data, path2_data, connect_end1, connect_start2):
        """Gabungkan dua path data."""
        # Parse path1
        p1 = paths.Path(path1_data)
        p2 = paths.Path(path2_data)

        # Jika perlu reverse path2
        if not connect_start2:
            p2 = p2.reverse()

        # Gabungkan: path1 + path2
        # Buat path baru
        merged = paths.Path()
        for cmd in p1:
            merged.append(cmd)
        for cmd in p2:
            merged.append(cmd)

        return merged.to_path_string()

    def try_merge_paths(self, path_nodes, tolerance):
        """Coba gabungkan path-path yang ujungnya berdekatan."""
        merged = []
        used = set()

        for i, node1 in enumerate(path_nodes):
            if i in used:
                continue

            # Start grup dengan path ini
            group = [node1]
            used.add(i)

            # Cari path lain yang bisa dihubungkan
            changed = True
            while changed:
                changed = False
                for j, node2 in enumerate(path_nodes):
                    if j in used:
                        continue

                    # Cek apakah bisa dihubungkan dengan grup saat ini
                    can_merge, merge_info = self.can_merge_group(group, node2, tolerance)
                    if can_merge:
                        group.append(node2)
                        used.add(j)
                        changed = True
                        break

            merged.append(group)

        return merged

    def can_merge_group(self, group, new_node, tolerance):
        """Cek apakah new_node bisa dihubungkan dengan grup path."""
        new_ends = self.get_path_endpoints(new_node)
        if not new_ends:
            return False, None

        new_start, new_end = new_ends

        for node in group:
            group_ends = self.get_path_endpoints(node)
            if not group_ends:
                continue

            g_start, g_end = group_ends

            # Cek 4 kemungkinan koneksi:
            # group_end -> new_start
            if self.distance(g_end, new_start) <= tolerance:
                return True, ('end', 'start')
            # group_end -> new_end  
            if self.distance(g_end, new_end) <= tolerance:
                return True, ('end', 'end')
            # group_start -> new_start
            if self.distance(g_start, new_start) <= tolerance:
                return True, ('start', 'start')
            # group_start -> new_end
            if self.distance(g_start, new_end) <= tolerance:
                return True, ('start', 'end')

        return False, None

    def effect(self):
        # Ambil semua path yang diselect
        selected_paths = []
        for node in self.svg.selection:
            if node.tag == inkex.addNS('path', 'svg'):
                selected_paths.append(node)

        if len(selected_paths) < 2:
            inkex.utils.errormsg("Pilih minimal 2 path untuk digabungkan.")
            return

        tolerance = self.options.tolerance

        # Kelompokkan berdasarkan warna stroke
        color_groups = {}
        for node in selected_paths:
            color = self.get_stroke_color(node)
            if color not in color_groups:
                color_groups[color] = []
            color_groups[color].append(node)

        # Proses tiap grup warna
        for color, path_nodes in color_groups.items():
            if len(path_nodes) < 2:
                continue

            # Cari dan gabungkan path yang terhubung
            merged_groups = self.try_merge_paths(path_nodes, tolerance)

            # Buat path baru untuk setiap grup yang berhasil digabung
            for group in merged_groups:
                if len(group) == 1:
                    continue  # Tidak perlu merge

                # Gabungkan semua path dalam grup
                # Simplified: ambil path pertama sebagai base, append yang lain
                base_node = group[0]
                merged_d = base_node.get('d', '')
                base_style = base_node.style

                for next_node in group[1:]:
                    next_d = next_node.get('d', '')
                    # Cek orientasi untuk penggabungan yang benar
                    base_ends = self.get_path_endpoints(base_node)
                    next_ends = self.get_path_endpoints(next_node)

                    if base_ends and next_ends:
                        b_start, b_end = base_ends
                        n_start, n_end = next_ends

                        # Cari koneksi terbaik
                        best_dist = float('inf')
                        best_config = None

                        configs = [
                            (b_end, n_start, False, False),
                            (b_end, n_end, False, True),
                            (b_start, n_start, True, False),
                            (b_start, n_end, True, True),
                        ]

                        for p1, p2, rev1, rev2 in configs:
                            d = self.distance(p1, p2)
                            if d < best_dist and d <= tolerance:
                                best_dist = d
                                best_config = (rev1, rev2)

                        if best_config:
                            rev1, rev2 = best_config
                            try:
                                p1_obj = paths.Path(merged_d)
                                p2_obj = paths.Path(next_d)

                                if rev1:
                                    p1_obj = p1_obj.reverse()
                                if rev2:
                                    p2_obj = p2_obj.reverse()

                                # Gabungkan
                                merged = paths.Path()
                                for cmd in p1_obj:
                                    merged.append(cmd)
                                for cmd in p2_obj:
                                    merged.append(cmd)

                                merged_d = merged.to_path_string()

                                # Hapus node yang sudah digabung
                                if next_node.getparent() is not None:
                                    next_node.getparent().remove(next_node)
                            except Exception as e:
                                inkex.utils.errormsg(f"Error merging: {e}")

                # Update path utama
                base_node.set('d', merged_d)

                # Pastikan style tetap sama
                if base_style:
                    base_node.style = base_style

if __name__ == '__main__':
    MergeConnectedPaths().run()
